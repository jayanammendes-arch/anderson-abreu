export const ALL_TREATMENT_ICON_NAMES = [...new Set(Object.values(TREATMENT_ICON_GROUPS).flat())]
export const TREATMENT_ICON_NAMES = Object.keys(TREATMENT_ICONS)

export function getTreatmentIcon(name?: string): LucideIcon {
  if (name && TREATMENT_ICONS[name]) return TREATMENT_ICONS[name]
  if (name) {
    const lower = name.toLowerCase()
    if (TREATMENT_ICONS[lower]) return TREATMENT_ICONS[lower]
  }
  return Sparkles
}
